int	ft_atoi(char *str)
{
	int		mflg;
	long	n;

	n = 0;
	mflg = 0;
	while ((*str >= 9 && *str <= 13) || *str == ' ')
		str++;
	while (*str == '+' || *str == '-')
	{
		if (*str == '-')
			mflg++;
		str++;
	}
	while (*str >= '0' && *str <= '9')
	{
		n = n * 10 + (*str - '0');
		str++;
	}
	if (mflg % 2 == 1)
		n = -n;
	return (n);
}
